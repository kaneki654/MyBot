import numpy as np

# Mock definitions to support the code
def softmax(x):
    e_x = np.exp(x - np.max(x, axis=-1, keepdims=True))
    return e_x / np.sum(e_x, axis=-1, keepdims=True)

def mock_forward_pass(input_ids, model_params):
    # Dummy forward pass returning random logits for demonstration
    batch_size, seq_len = input_ids.shape
    vocab_size = model_params['vocab_size']
    return np.random.randn(batch_size, seq_len, vocab_size)

# --- 1. Perplexity ---
def calculate_perplexity(model_params, validation_batches):
    """
    Computes perplexity on a validation dataset.
    Lower perplexity means the model is less "surprised" by the true text.
    """
    total_loss = 0.0
    total_tokens = 0
    
    # In a real scenario, you'd iterate through your validation dataloader
    for (X_val, Y_val) in validation_batches:
        batch_size, seq_len = X_val.shape
        
        # 1. Forward pass (no gradients needed for evaluation)
        logits = mock_forward_pass(X_val, model_params)
        
        # 2. Compute probabilities
        probs = softmax(logits)
        
        # 3. Extract probabilities of the true target tokens
        # Flatten arrays for easier indexing
        probs_flat = probs.reshape(-1, model_params['vocab_size'])
        targets_flat = Y_val.reshape(-1)
        
        # Get probabilities of correct next words
        correct_probs = probs_flat[np.arange(len(targets_flat)), targets_flat]
        
        # 4. Calculate Negative Log Likelihood (NLL)
        eps = 1e-12
        batch_nll = -np.sum(np.log(correct_probs + eps))
        
        total_loss += batch_nll
        total_tokens += (batch_size * seq_len)
        
    # Average NLL over all tokens
    avg_nll = total_loss / total_tokens
    
    # Perplexity is the exponentiation of the cross-entropy loss (NLL)
    perplexity = np.exp(avg_nll)
    
    return perplexity, avg_nll

# --- 2. BLEU Score (Simplified) ---
from collections import Counter

def ngrams(tokens, n):
    return [tuple(tokens[i:i+n]) for i in range(len(tokens)-n+1)]

def calculate_bleu(reference, candidate, max_n=4):
    """
    Computes a simplified BLEU score for text generation quality.
    reference: List of token IDs representing the ground truth text.
    candidate: List of token IDs generated by the model.
    """
    bp = 1.0 # Brevity Penalty
    if len(candidate) < len(reference):
        bp = np.exp(1 - len(reference) / len(candidate))
        
    bleu_scores = []
    
    # Calculate precision for 1-gram to max_n-grams
    for n in range(1, max_n + 1):
        ref_ngrams = Counter(ngrams(reference, n))
        cand_ngrams = Counter(ngrams(candidate, n))
        
        if not cand_ngrams:
            bleu_scores.append(0.0)
            continue
            
        # Count overlapping n-grams
        overlap = 0
        for ngram in cand_ngrams:
            # We cap the overlap by the maximum number of times the n-gram appears in the reference
            overlap += min(cand_ngrams[ngram], ref_ngrams[ngram])
            
        precision = overlap / sum(cand_ngrams.values())
        
        # Add small smoothing value to avoid log(0) if precision is 0
        bleu_scores.append(precision if precision > 0 else 1e-10)
        
    # BLEU score is the geometric mean of the n-gram precisions multiplied by the Brevity Penalty
    # Using log domain for numerical stability
    log_precisions = np.log(bleu_scores)
    geometric_mean = np.exp(np.mean(log_precisions))
    
    return bp * geometric_mean

